from django.conf import settings
from django.db import models

from apps.core.models import InstitutionScopedModel, StoredFile


class Conversation(InstitutionScopedModel):
    """A chat. Section conversations take their members from enrollment and teacher
    assignments, so access follows the timetable without any manual member lists."""

    class Kind(models.TextChoices):
        SECTION = "section"
        GROUP = "group"
        DIRECT = "direct"

    kind = models.CharField(max_length=16, choices=Kind.choices)
    section = models.OneToOneField(
        "academic.Section",
        null=True,
        blank=True,
        on_delete=models.CASCADE,
        related_name="conversation",
    )
    title = models.CharField(max_length=200, blank=True)
    # "<lower user id>:<higher user id>" for one-to-one chats, so each pair has exactly one.
    direct_key = models.CharField(max_length=41, null=True, blank=True, unique=True)
    last_message_at = models.DateTimeField(null=True, blank=True, db_index=True)

    class Meta:
        constraints = [
            models.CheckConstraint(
                condition=~models.Q(kind="section") | models.Q(section__isnull=False),
                name="section_conversation_has_section",
            )
        ]

    def __str__(self):
        return self.title or f"{self.get_kind_display()} {self.pk}"

    @property
    def channel(self) -> str:
        return f"chat:conv_{self.pk}"

    @property
    def typing_channel(self) -> str:
        return f"typing:conv_{self.pk}"


class ConversationMember(InstitutionScopedModel):
    """Per-person state in a conversation (read position, mute). For section conversations a
    row is created on first visit; access itself is decided by enrollment, not by this row."""

    conversation = models.ForeignKey(
        Conversation, on_delete=models.CASCADE, related_name="members"
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="conversations"
    )
    last_read_message_id = models.PositiveBigIntegerField(default=0)
    muted = models.BooleanField(default=False)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["conversation", "user"], name="uniq_conversation_member"
            )
        ]


class Message(InstitutionScopedModel):
    conversation = models.ForeignKey(
        Conversation, on_delete=models.CASCADE, related_name="messages"
    )
    sender = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="messages"
    )
    client_id = models.UUIDField(help_text="Generated by the sender's device; makes retries safe")
    body = models.TextField(max_length=4000, blank=True)
    attachments = models.ManyToManyField(StoredFile, blank=True, related_name="+")
    edited_at = models.DateTimeField(null=True, blank=True)
    deleted_at = models.DateTimeField(null=True, blank=True)
    deleted_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+"
    )

    class Meta:
        indexes = [models.Index(fields=["conversation", "id"])]
        constraints = [
            models.UniqueConstraint(
                fields=["conversation", "sender", "client_id"], name="uniq_message_client_id"
            )
        ]

    def __str__(self):
        return f"Message {self.pk} in {self.conversation_id}"
